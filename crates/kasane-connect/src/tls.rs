pub struct TlsConfigs {
    pub server: Arc<ServerConfig>,
    pub client: Arc<ClientConfig>,
    pub cert_der: Vec<u8>,
}

impl TlsConfigs {
    pub fn new(cert_der: Vec<u8>, key_der: Vec<u8>) -> Result<TlsConfigs, rustls::Error> {
        let provider = Arc::new(rustls::crypto::ring::default_provider());
        let cert = CertificateDer::from(cert_der.clone());
        let key = PrivateKeyDer::Pkcs8(PrivatePkcs8KeyDer::from(key_der));

        let server = ServerConfig::builder_with_provider(provider.clone())
            .with_protocol_versions(&[&rustls::version::TLS13])?
            .with_client_cert_verifier(Arc::new(AnyClientCert {
                provider: provider.clone(),
            }))
            .with_single_cert(vec![cert.clone()], key.clone_key())?;
        let client = ClientConfig::builder_with_provider(provider.clone())
            .with_protocol_versions(&[&rustls::version::TLS13])?
            .dangerous()
            .with_custom_certificate_verifier(Arc::new(AnyServerCert {
                provider: provider.clone(),
            }))
            .with_client_auth_cert(vec![cert], key)?;
        Ok(TlsConfigs {
            server: Arc::new(server),
            client: Arc::new(client),
            cert_der,
        })
    }
}

pub fn cert_fingerprint(cert: &[u8]) -> [u8; 32] {
    Sha256::digest(cert).into()
}
